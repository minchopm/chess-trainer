import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('../src/app/pages/guide/', import.meta.url);
const copy = JSON.parse(await readFile(new URL('content.json', base), 'utf8'));
const locales = JSON.parse(await readFile(new URL('./locales.json', import.meta.url), 'utf8')).locales;
for (const { slug } of locales) {
  const c = copy[slug];
  if (!c?.title || !c.intro || c.faq?.length !== 4 || !c.sections?.length) throw new Error(`Incomplete guide: ${slug}`);
}
await writeFile(new URL('content.ts', base), '// Generated by tools/build-practice-guide.mjs. Edit content.json.\nexport const GUIDE_COPY = ' + JSON.stringify(copy, null, 2) + ' as const;\n');
await writeFile(new URL('labels.ts', base), '// Generated by tools/build-practice-guide.mjs.\nexport const GUIDE_LABELS: Record<string, string> = ' + JSON.stringify(Object.fromEntries(Object.entries(copy).map(([k,v]) => [k,v.title])), null, 2) + ';\n');
